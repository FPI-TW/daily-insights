export function createI18n(locale: Locale) {
  const instance = createInstance()
  void instance.use(initReactI18next).init({
    lng: locale,
    fallbackLng: "zh-hant",
    lowerCaseLng: true,
    resources,
    initAsync: false,
    interpolation: { escapeValue: false },
  })
  return instance
}
